test("a resident hears the player's earlier message and not another person's", async () => {
  const sent = admitPlayer(emptyLedger(), { type: "message", to: "samira", text: "码头还有空位" }, 540);
  const town = createNpcTown({ residents, minute: 600, decide: () => ({ type: "stay" }), resume: { residents: [], society: sent.ledger } });
  let samira = "";
  let luis = "";
  await town.commit(async (view) => {
    if (view.me.id === "samira") samira = view.heard[0]?.text ?? "";
    if (view.me.id === "luis") luis = view.heard.map((item) => item.text).join("");
    return { type: "stay" };
  });
  assert.equal(samira, "码头还有空位");
  assert.equal(luis, "");
});

test("the decision prompt tells the model what it and the player may do", async () => {
  const town = createNpcTown({ residents, minute: 540, decide: () => ({ type: "stay" }) });
  let rules = "";
  let mayNot: { action: string; reason: string }[] = [];
  let playerMay: string[] = [];
  let instructions = "";
  await town.commit(async (view) => {
    if (view.me.id !== "luis") return { type: "stay" };
    const input = JSON.parse(npcDecisionInput(view)) as { rules: string; limits: { may: string[]; mayNot: { action: string; reason: string }[]; playerMay: string[] } };
    rules = input.rules;
    mayNot = input.limits.mayNot;
    playerMay = input.limits.playerMay;
    instructions = npcMoveQuestion(view).instructions;
    return { type: "stay" };
  });
  assert.match(rules, /does not accept a quote/);
  assert.match(rules, /The player, between rounds/);
  assert.ok(mayNot.some((item) => item.action === "message-settle" && item.reason === "NPC_MESSAGE"));
  assert.ok(mayNot.some((item) => item.action === "administer" && item.reason === "NPC_AUTHORITY"));
  assert.ok(playerMay.includes("message"));
  assert.match(instructions, /limits\.mayNot/);
});

